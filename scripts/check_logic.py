#!/usr/bin/env python3
"""筋の点検：一文ずつ、筋が通っているか・本当のことかを確かめる。

旧 tools/logic_check.py（kyuketsu-mahou-syojo04、2026-10-01）に、旧 scene_check の「理屈・段階」を統合した。
オーナーの直しの多くは文体ではなく筋だった（指示語の指す先がない、前の行とつながらない、台帳と食い違う、
誰の台詞か分からない、人の動きが不自然）。それを書いた側で先に拾う。

2026-10-02：その話の作者の決定（章のあらすじの節とメモの節。agent.episode_plan）を渡すようにした。
渡していなかったため、点検役は決めた筋や会話で決めた引きを知らず、古い BAD-EXAMPLES で「直す」を出し続け、
直し案がそれに合わせて筋から外れた（EP023）。読者として見る項目（指示語・つながり・読み・知らない言葉）では
作者の決定を使わず、決定との照合の項目（事実・立場・理屈・段階）でだけ使う。
2026-10-13：BAD-EXAMPLES（オーナーの直しの組）を外した。過去の型は拾えても次の欠陥は拾えず、資料が 99KB に膨れて外れを増やしていた。
同じ型の場面を書くときだけ書き手に渡す（作品 AGENTS）。

使い方（作品リポジトリのルートで）:
  python ../pachi-book/scripts/check_logic.py EP022 V2
  python ../pachi-book/scripts/check_logic.py EP022 V2 --old "元の文" --new "直した文"
      # チャットで出す直し案を、本文に差し込んだ形で点検する（差し込んだ所と前後三文だけ）
出力: 本文全体は episodes/EPxxx/notes/logic-Vn-<agent>-<回>.md。直し案は標準出力のみ。
通常は check_all.py から呼ばれる。
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import agent as A  # noqa: E402

CHECKS = """一文ずつ、次の八つを確かめてください（2026-10-14 組み替え。問いは八つだけ。これ以外は挙げない）。
1. 事実（前の話との矛盾・話の中の破綻）：これまでのあらすじ・前の話の採用版・台帳のカードと「知っていること」と食い違う（いない人がいる、知らないはずのことを知っている、
   前の話で決まった事実や台詞と違う、名前や行事の取り違え）。同じ話の中で前後が合わない（場所・持ち物・誰がどこにいるか）もここ。
   人物の関係や反応が「今の距離と反応」と合わない（まだ推しでない子を推しと呼ぶ、第1章のはじめの反応が今の距離で出ている）もここ。
   初稿の点検でも採用前の点検でも、この 1 をいちばん先に見る（2026-10-14 オーナー）。
2. 誰が何を知るか：メモの「誰が何を知る」から外れた（秘密を話した、知らないはずの前提で話す、秘密を知らない相手に中身を送った）。
3. 話し手：誰の台詞か一度で分からない。決まりごと一枚の呼び方・口調と違う（地の文の敬称は機械が見るので挙げない）。
4. 立場：話している二人の立場で台詞が成り立つか。相手本人を三人称で呼んでいないか。その人物がこの状況で本当にそれを言うか。
5. 指示語：「あの」「その」「それ」「あいつ」の指す先が直前の数行にない。読者が一度で分からない。
6. 人の動き：その場の人たちの動きや反応が不自然（配信のコメントが全員同じ立場、など）。特別扱い（列を飛ばす、係が一人にだけ合図する）。主語が断りなく変わる。
7. 決定：メモの「誰が何を知る」と「触れないこと」の中身から外れた所。見せ場の台詞・引き・使わないものは機械（check_decisions・check_reuse）が見るので挙げない。
   散文の運び（どの順で何が目に入るか、どの場面で何を思うか）との違いは挙げない。書き手が場面の中を発明するのは決まり。
8. 読者が知らない言葉：本文で初めて出る固有の言葉・事情で、前の話にもあらすじにもないもの（常識で分かる語は挙げない）。

挙げないもの：つながり・読み・リズム・先のない描写・数字（機械が見る）、理屈（1 と 7 に含める）、現場の細部（書き手が決まりごと一枚で守る）、
読者が常識で補える動作や段取りの省略（カップを持ってから置く、店に入ってから座る、など。2026-10-10 オーナー）。

資料の使い方：
- 読者として見る項目（5 指示語・8 知らない言葉）では、作者の決定を読んでいない読者として、本文・前の話・あらすじだけで判断する。
- 決定との照合（1・2・7）では、作者の決定（散文の節とメモの節）に書いてあることは決まっている。それ自体を直す理由にしない。台帳の古い記述と決定がぶつかれば、決定のほうが新しい。
- 必須は 1〜7。参考は 8。"""

PROMPT_FULL = f"""あなたはこの連載の校閲者です。文体ではなく、筋と事実を見ます。
下に、これまでのあらすじ、決まりごと一枚と台帳のカードと「知っていること」、前の話、この話の作者の決定（散文のあらすじ・メモ）、今回の本文があります。

{CHECKS}

{A.OUTPUT_RULES}

次の形式だけで答えてください。ツールは使わないでください。表の列は増やさず減らさず、一行に一つ。引っかかりがなければ表の行を書かず「なし」とだけ書く。

## 必須（1〜7。本文の順）
| ID | 場所（本文を短く引用） | 種類 | 何がおかしいか | 今の文 | 案A | 案B | 推奨 |
|---|---|---|---|---|---|---|---|
| L01 | 「…」 | 事実 | … | 「…」 | 「…」 | 「…」 | A：理由を一言 |

種類は 事実／誰が何を知る／話し手／立場／指示語／人の動き／決定 のどれか。

## 参考（8）
| ID | 場所（本文を短く引用） | 種類 | 何がおかしいか | 今の文 | 案A | 案B | 推奨 |
|---|---|---|---|---|---|---|---|
| L21 | 「…」 | 読者が知らない言葉 | … | 「…」 | 「…」 | 「…」 | … |
"""

PROMPT_SNIPPET = f"""あなたはこの連載の校閲者です。文体ではなく、筋と事実を見ます。
作者が本文の一部を直そうとしています。下の「直したあとの本文」の【直した所】の前後だけを点検してください。
【直した所】の中の文と、その直前・直後の三文だけを挙げてください。それより離れた文の問題は挙げないでください。
特に、直した文が、この話の中ですでに決まっていること（誰がどこにいるか、誰が何を言ったか、人物の気持ちの向き）と食い違っていないかを、
その決まりの文を本文から引用して確かめてください。
見るのは CHECKS の 1 事実・2 誰が何を知るか・3 話し手・7 決定 だけです（2026-10-14。差分の点検は文脈だけ）。

{CHECKS}

次の形式だけで答えてください。ツールは使わないでください。

## 判定
- 通る／直す（一行で理由。「直す」は、読者が一度で詰まる・事実と食い違う・作者の決定から外れた、のどれかのときだけ。好みや程度の問題では「通る」にして、下に書く）

## 決定との照合
- 守れている／外れた：直した所が作者の決定（その場面の台詞・本当に気にしていること・誰が何を知るか）を残しているか。外れたなら何が抜けた／足されたか

## 引っかかった文
- 「引用」：番号：何がずれているか：ぶつかる本文の文（引用）
"""


def context(ep):
    """点検の束（2026-10-14 組み替え。research/protocol-v3-2026-10-14.md §3d）：
    決まりごと一枚・出る人物のカード・メモが指定する world の節（A.canon_context）、前の話までのあらすじ、前の話、この話の決定。
    主人公の掟・語り方（CH-01-voice）・オーナーの目・LONG-ARCS・台帳の記録は渡さない（73k 字で一行の決まりが拾えなかった）。"""
    n = int(ep[2:])
    return A.SEP.join([A.section("これまでのあらすじ", A.synopsis_before(n)), A.canon_context(ep),
                       A.section("前の話", A.prev_episode(ep)),
                       A.section("この話の作者の決定（章のあらすじ・メモ）", A.episode_plan(ep))])


def prompts(ep, ver, old=None, new=None):
    target = A.episode_text(ep, ver)
    if old is None:
        return f"{PROMPT_FULL}{A.SEP}{context(ep)}{A.SEP}# 今回の本文\n\n{target}\n"
    if old not in target:
        sys.exit("--old の文字列が本文に見つからない")
    target = target.replace(old, f"【直した所】{new}【ここまで】", 1)
    return f"{PROMPT_SNIPPET}{A.SEP}{context(ep)}{A.SEP}# 直したあとの本文\n\n{target}\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("episode")
    ap.add_argument("version")
    ap.add_argument("--old")
    ap.add_argument("--new")
    ap.add_argument("--new-file")
    ap.add_argument("--runs", type=int, default=1)
    A.add_model_args(ap)
    a = ap.parse_args()
    snippet = a.old is not None
    new = a.new if a.new is not None else (Path(a.new_file).read_text(encoding="utf-8").rstrip("\n") if a.new_file else None)
    if snippet and new is None:
        sys.exit("--new か --new-file が要る")
    prompt = prompts(a.episode, a.version, a.old, new)
    jobs = [(n, prompt, (n, k)) for n in A.agents(a.agent) for k in range(1, a.runs + 1)]
    for (name, k), text, err in A.run_many(jobs, a.model, a.effort):
        if err:
            print(f"{name}: {err}")
        elif snippet:
            print(f"=== {name} {k}回目 ===\n{text}\n")
        else:
            out = A.notes_dir(a.episode) / f"logic-{a.version}-{name}-{k}.md"
            print(A.write(out, f"# 筋の点検 {a.episode} {a.version}（{name} {k}回目）\n\n{text}"))


if __name__ == "__main__":
    main()
