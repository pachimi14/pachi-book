#!/usr/bin/env python3
"""声の点検：良い例とダメな例を並べて渡し、本文の場面ごとに「どちらに近いか」を判定させる。

旧 tools/voice_review.py（kyuketsu-mahou-syojo04、2026-09-30）に、旧 scene_check の「比喩・緊張」と、
「足りない所」（主人公の内心・場面の描写が足りず、オーナーが足した所）を統合した。
一回ごとのぶれが大きい（2026-10-01 の検証で、同じ版でも挙げる文が変わった）ので、既定で2回回す。
二回の重なりは check_all.py がまとめる。
2026-10-13：良い例集（第1章の一言集）とダメな例集（99KB）を外し、WRITE-BRIEF と直前の採用話を渡す。
良い例集が第1章の反応を「良い」と教えるので繰り返しを正解と判定し、ダメな例集は過去の型しか拾えなかった（原因の切り分け）。
オーナーの直しの組は、同じ型の場面のものを --bad-examples で渡すときだけ。

使い方（作品リポジトリのルートで）:
  python ../pachi-book/scripts/check_voice.py EP018 V10
出力: episodes/EPxxx/notes/voice-Vn-<agent>-<回>.md
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import agent as A  # noqa: E402

PROMPT = f"""あなたはこの連載の編集者です。作者の文の癖を直す係です。
下に資料があります。
1. 書き手の一枚（WRITE-BRIEF）：地の文の仕事と形、場面の型ごとの見本の話。この作品の「良い」はここで決まる。第1章のはじめの反応を良い例にしない。
2. 直前の話（採用版）：今の段階の語り方と関係の距離。今回の本文はこれの続きとして読む。
3. 主人公の掟・語り方、オーナーの目。
4. 今回の本文。
5. 一言の照準の問い（あるとき）。
6. 同じ型の場面でオーナーが直した例（あるときだけ。無ければ気にしない）。

今回の本文を場面ごとに読み、次を見てください。
- AIっぽい文：オーナーが一番嫌う型です。該当するものを挙げてください。
  AならX、BはYと並べて二つ目で落とす対句／気持ちを「覚悟」「言葉を持つ」のような抽象語で外から名づける文／
  「どこを探しても見つからなかった」のような否定の強調の決まり文句／段落や場面の最後を格言・一般論・抽象のまとめで閉じる文／
  人物を一言で評して閉じる文（「〜は、言ったことを全部やる人だ」）。
  挙げないもの（2026-10-13 オーナー）：段落の最後に置かれた「具体の評価」の短い一文（我ながら苦しい。たぶん逆効果だった。嬉しくない。字面が最悪だ。審査員は俺一人だったが、通った。）。
  これはこの語り手の声そのもので、EP001〜012 の段落はほぼこの形で閉じている。感情の名前ではなく評価で、その場で思ったことなら AI っぽい文ではない。
  直す方向は「削る」だけにしない。「その場で思ったことに言い換える」のように、判断の文を残す方向を書く。
- 地の文の仕事（2026-10-13）：空行で区切った地の文の塊が、見たことの報告（〜た。）だけで終わっていないか。
  良い例の塊は「報告 → ファンの物差しで判断 → 理由か言い直し → 短い評価で落とす」の順に仕事が変わる。報告だけで終わる塊が続く場面を挙げ、
  「報告のあとに判断・理由・言い直しを置く」と方向を書く（数を減らすためではなく、語り手の仕事を増やすため）。
- オーナーの目に近い文：主人公がカメラになっている、説明の一文、昔と今の対比、など（資料6があれば、その組の「元」に近い文も）。
- 段階：直前の話と比べて、主人公の反応が戻っていないか（固まる・早口・床を転がる・声が裏返る、のような第1章のはじめの反応が今の距離で出ている）。くどさは言い回しではなく反応の段階で見る。
- 比喩：その場で絵が浮かぶ近さか。作りすぎ・普通は言わない言い回しになっていないか。
- 言葉と物：数え方・単位・動詞がその物の絵に合っているか（血を「一本」と数える、など。2026-10-13 オーナー「言葉選びがおかしい部分が多い」）。
- 緊張：この瞬間に主人公が本当に気にしていること（怖いこと、嬉しいこと、隠したいこと）が書けているか。表面の冗談や「ファンらしい一言」で埋めていないか。
- 足りない所：主人公の内心や、その場の人の様子が足りず、読者が置いていかれる所。大事な人との場面（久しぶりに会う人、推しとの初めての握手など）を数行で流していないか。
- 書きすぎ：主人公の心配・説明が重なって、同じ気持ちを二度書いている所。

- 一言の照準（資料5があるとき）：主人公のらしい一言（実況・考察・ツッコミ）を一つずつ、資料5の問いに当てる。
  一言を減らすためではない。見当違い（その瞬間の本気とずれている）か、この場面には要らない（重い場面に冗談・たとえ、言い直し、一言のためだけの場面、型の使い回し）かを見る。

{A.OUTPUT_RULES}

次の形式だけで答えてください。ツールは使わないでください。褒めるための評価は要りません。

## AIっぽい文（抽象のまとめ・対句・決まり文句・抽象語の名づけ。具体の評価の一文は挙げない）
- 「本文を引用」：どの型か：直す方向（一言。削るだけにしない）

## 地の文の仕事（報告だけで終わる塊が続く場面）
- 場面（冒頭の数語）：塊の数：直す方向（一言）

## ダメな例に近い文・比喩
- 「本文を引用」：どの種類か：直す方向（一言）

## 緊張・足りない所・書きすぎ
- 場面（冒頭の数語）：緊張／足りない／書きすぎ：何が抜けているか・重なっているか（一行）

## 一言の照準（資料5があるとき。合っているものは挙げない）
- 「本文を引用」：見当違い／要らない：どの問いに当たるか（番号）：その瞬間の主人公の本気は何か（一行）

## 面白さの仕組み（場面ごと。2026-10-01）
良い例の面白さは、主人公の本気（何に夢中か、何を気にしているか）と、その場の状況とのずれから出ている。場面ごとに、笑い・盛り上がりの出どころを見る。
- 場面（冒頭の数語）：本気（この瞬間に主人公が本当に気にしていること。一行）：出どころ（本気のずれ／状況のずれ／外から足した一言／なし）：報酬（笑う／報われる／気になる／冷える／なし）
- 「外から足した一言」：その場面の本気から出ていない笑い（ファンらしい決まり文句、場面と関係ないたとえ、言い直し）。本文を引用し、削るか、本気から出る言い方に言い換える方向を一言。
- 「報酬：なし」の場面：何を受け取る場面か分からない所。足して埋めず、場面を短くする・前後とまとめる方向を一言。

## 場面ごとの判定
- 場面（冒頭の数語）：良い例に近い／ダメな例に近い／どちらとも言えない：理由を一行

## 一番よかった場面
- 本文を引用して一つ
"""


def prompt(ep, ver, bad_examples=None):
    return A.SEP.join([PROMPT, A.section("1. 書き手の一枚（WRITE-BRIEF）", A.doc("write_brief")),
                       A.section("2. 直前の話（採用版）", A.prev_episode(ep)),
                       A.section("3. 主人公の掟・語り方", A.doc("voice_rules")), A.section("3. オーナーの目", A.doc("owner_eye")),
                       A.section("4. 今回の本文", A.episode_text(ep, ver)),
                       A.section("5. 一言の照準の問い", A.doc("line_aim")),
                       A.section("6. 同じ型の場面でオーナーが直した例", A.read(bad_examples) if bad_examples else "")]) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("episode")
    ap.add_argument("version")
    ap.add_argument("--runs", type=int, default=2)
    ap.add_argument("--bad-examples", help="同じ型の場面のオーナーの直しの組（ファイル）。既定では渡さない（2026-10-13）")
    A.add_model_args(ap)
    a = ap.parse_args()
    p = prompt(a.episode, a.version, a.bad_examples)
    jobs = [(n, p, (n, k)) for n in A.agents(a.agent) for k in range(1, a.runs + 1)]
    for (name, k), text, err in A.run_many(jobs, a.model, a.effort):
        if err:
            print(f"{name}: {err}")
            continue
        out = A.notes_dir(a.episode) / f"voice-{a.version}-{name}-{k}.md"
        print(A.write(out, f"# 声の点検 {a.episode} {a.version}（{name} {k}回目）\n\n{text}"))


if __name__ == "__main__":
    main()
