#!/usr/bin/env python3
"""メモ・あらすじの監査：章・ブロックのあらすじと各話のメモを、オーナーに見せる前に点検する。

旧 tools/memo_check.py（kyuketsu-mahou-syojo04、2026-10-01）を移し、二つの問いを足した（2026-10-01）：
  7. 作者が決める分かれ目（持ち場・引き・設定など）を、書く前に二択で出す
  8. 作者が体験していない現場の細部を、書く前に洗い出す
さらに、作品の pachi.json に market（市場の調べ）があれば、章のあらすじ（chapters/ のファイル）の通し読みに「市場の型」を足す（2026-10-01）。
伸びた作品・伸びなかった作品の型に照らした参考で、推測。採用済みの話を変える提案はしない。
9/30 の介入の約3割は、作者が本文を読んでから決め直した分かれ目だった。本文の書き直しをメモの段階へ前倒しする。

使い方（作品リポジトリのルートで）:
  python ../pachi-book/scripts/check_memo.py chapters/CH-03-STORY.md        # 章のあらすじ（通し読みの点検つき）
  python ../pachi-book/scripts/check_memo.py blocks/CH-02-B-memos.md
  python ../pachi-book/scripts/check_memo.py blocks/CH-02-B-memos.md --episodes EP022 EP023
  python ../pachi-book/scripts/check_memo.py blocks/CH-02-B-memos.md blocks/CH-02-C-memos.md --after EP022
      # 波及の監査：採用した話がメモからどう変わったかと、あとの話のメモに出る影響。採用のたびに回す。
出力: blocks/notes/memo-<メモ名>-<agent>-<回>.md（既定で2回。ぶれを補う）
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import agent as A  # noqa: E402

PROMPT = """あなたはこの連載の担当編集です。作者が本文を書く前のメモ（ブロック単位の各話の設計）を監査します。
本文はまだありません。メモの穴は、そのまま本文の書き直しになります。下に、台帳・長期の骨格・これまでのあらすじ・オーナーの目・オーナーが直した例・メモがあります。

対象の各話について、次の八つを確かめてください。あらすじ（章・ブロックを通しで書いた文章）の場合は、そのあと「通し読み」の三つも確かめてください。問題を無理に探さないでください。ただし、当たるものは全部挙げてください。

1. 場面の目的：どの場面にも「主人公が本当に気にしていること」と、その話の「面白いところ」「報酬」につながる役目が書いてあるか。並び（場面の順）に名前だけあって中身のない場面はないか。字数合わせに見える場面はないか。
2. 引き：次の話を開きたくなる新しい何か（情報・決断・異変）があるか。笑いだけで閉じていないか。ほかの話へ移した要素に頼ったままになっていないか（移したあと埋め直していない欄）。次の話の展開をばらしすぎていないか。
3. 見せ場の台詞：一行ずつ、指示語の指す先・意味が一度で通るか・台帳と食い違わないか・誰の台詞か・その人物の口調か（これまでの台詞と合うか）を確かめる。意味の通らない台詞（例：「灰が、見たものを人に渡した」は灰が自分で動いたように読める）を挙げる。
4. メモの中の食い違い：日付・場面の並び・引き・字数の欄が、書き直したあとの内容と合っているか。古い版の記述が残っていないか。
5. 話どうしの重なりと受け渡し：同じ出来事や同じ気持ちを二話で書いていないか（視点違いの回と重なる、など）。前の話の引きを次の話の冒頭が受けているか。あとの話で使う札（正体・敵の台詞など）を早く切っていないか。
6. 台帳にない設定・数字：メモで新しく足している設定・数字・現場の細部を一覧にする（オーナーの確認が要るもの）。
7. 作者が決める分かれ目（2026-10-01）：本文を書く途中で作者が決め直しそうな所を、書く前に二択で出す。
   人物の配置（誰がどこに立つか、誰が何の係か）、引きの一行、場面を入れるか削るか、設定の決め（ルール・能力・時期）、
   誰が誰に何を知らせるか、のうち、メモで一つに決めてあるが理由が書いていないもの、または決めていないもの。
   9/30 の記録では、作者の介入の約3割がこの種類で、本文を読んでから決め直していた（持ち場が3回変わった）。
8. 現場の知識（2026-10-01）：作者が体験していないかもしれない場（行事の段取り、係の動き、専門の手順、業界の言葉）を本文で細かく書く予定の場面。
   人と気持ちだけで書くか、先に調べるかを決める必要がある。

通し読み（あらすじのとき。2026-10-01）：章やブロックを一つの話として通しで読む。
A. 流れ：話から話へ、出来事と気持ちがつながって読めるか。同じ型の場面（明かす、怒る、言い返せない、など）や同じ報酬が続いていないか。中だるみ・急な飛びはないか。
B. 知っていること：誰がいつ何を知ったかを話ごとに追い、知らないはずのことを知っている・知ったことを忘れている所がないか。
C. 採用済みの話との食い違い：これまでのあらすじ・台帳と合わない所。合わせるために採用済みの話を直す必要があるなら、どの話の何かを挙げる。

次の形式だけで答えてください。ツールは使わないでください。

## 通し読み（あらすじのとき。メモだけなら「なし」）
- 流れ：OK／問題（どの話からどの話へ、何が）
- 知っていること：OK／問題（誰が、どの話で）
- 採用済みの話との食い違い：なし／一覧（EPxxx：何を直す必要があるか）

## 話ごとの監査
### EPxxx
- 場面の目的：OK／問題（メモを引用して一行）
- 引き：OK／問題
- 見せ場の台詞：OK／問題（台詞ごと）
- 食い違い：OK／問題
- 重なり・受け渡し：OK／問題
- 台帳にない設定・数字：なし／一覧
- 分かれ目：なし／一覧（「何を：案A／案B：メモの今の選び」）
- 現場：なし／一覧（場面：何の細部か）

## 書く前に必ず直す所（重い順）
- EPxxx：メモを引用：何が穴か：埋め方の案（一行。案そのものが新しい設定を足さないこと）

## オーナーに聞く二択（書く前に決めてもらう。多くて5つ）
- EPxxx：何を：A／B：どちらを選ぶと何が変わるか（一行）
"""


PROMPT_MARKET = """
## 市場の型（参考。あらすじの通し読みのときだけ。2026-10-01）
下の「市場の調べ」は、カクヨムの同じ系統の作品の題名・目次・タグから、伸びた作品と伸びなかった作品の違いをまとめたものです。本文は読んでいないので、どれも推測です。
これから書く話（採用済みの話は除く）を、次の五つで見てください。当たらないものは「OK」で済ませてください。
- 反応・得：各話に、読者が受け取る反応か得（誰かが気づく・評価が変わる・何かを手に入れる）があるか。ない話を挙げる。
- 準備の続き：山場の前の準備・会議・移動の回が何話続くか。2話以上続くなら挙げる。
- 主人公の強さ：主人公の力がはっきり見える場面が、何話あいているか（採用済みの話の最後に見えた所から数える）。
- 反応の広がり：反応がファン・身内の中で止まっていないか。外（ニュース・組織・世間）へ段が上がる話はどこか。
- 題名：題名が決まっていれば、その話の山場・オチを明かしていないか。

出し方（守ってください）：
- 推測なので、必須にしない。「参考」として出し、オーナーが採るかどうかを決める。
- 一律のきまりで直させない。当たった話ごとに、市場の調べのどの型に当たるか（作品名の例）と、変える案を二択で書く（A：今のまま／B：変える案）。
- 作品の売り・作者の好み・長期の骨格で決まっていることとぶつかるなら、そちらを優先し、ぶつかると書く。
- 採用済みの話を変える提案はしない。

答えの形式に、次の節を足してください（「書く前に必ず直す所」の前）。
## 市場の型（参考。推測）
- 反応・得：OK／ない話（EPxxx：一行）
- 準備の続き：OK／EPxxx〜EPyyy（何の準備か）
- 主人公の強さ：OK／EPxxx〜EPyyy で見えていない
- 反応の広がり：段が上がる話（EPxxx）／止まっている
- 題名：OK／EPxxx（何を明かしているか）
- 二択（多くて3つ）：EPxxx：何を：A 今のまま／B 案：どの型（作品名の例）・推測の強さ
"""

PROMPT_AFTER = """あなたはこの連載の担当編集です。ある話を採用しました。本文はメモどおりに書けたとは限らず、書く途中で場面を削ったり、引きを変えたり、台詞を直したりしています。
その変更が、あとの話のメモに波及していないかを監査します。

1. 差分：採用した話の「メモ（計画）」と「採用版の本文・まとめ」を比べ、変わった所を全部挙げる。
   - 削った場面・移した要素（どの話へ行く予定か、行き先がメモに書いてあるか）
   - 足した場面・台詞・新しく本文に出た事実（台帳に入れたか）
   - 引きの変更（次の話の冒頭がそれを受けているか）
   - あとの話で使う予定だった札（正体・敵の台詞・気づき）を、この話で先に使ったもの
2. 影響：そのあとの各話のメモについて、差分のせいで直す必要がある所を全部挙げる。
   - 受け渡し：前の話の引き・移ってきた要素を、メモが受けていない
   - 重なり：採用版でもう書いたことを、メモがもう一度書こうとしている
   - 食い違い：人物が知っていること・関係・状況・日付が、採用版と合わない
   - 札の空振り：先に使われた札を、メモが「初出」として扱っている
問題を無理に探さないでください。ただし、当たるものは全部挙げてください。

次の形式だけで答えてください。ツールは使わないでください。

## 差分（メモ → 採用版）
- 種類（削った／移した／足した／引き／先に使った札）：内容：行き先・影響する話

## あとの話のメモに必要な直し（話の順）
### EPxxx
- メモを引用：どの影響か：直し方（メモに書く文を一行で。新しい設定を足さない）
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("memo", nargs="+", help="メモのファイル（波及の監査では、採用した話のメモとあとのメモを並べる）")
    ap.add_argument("--after", help="採用した話（例 EP022）。波及の監査をする")
    ap.add_argument("--episodes", nargs="*", help="監査する話（省略するとメモの全話）")
    ap.add_argument("--runs", type=int, default=2)
    A.add_model_args(ap)
    a = ap.parse_args()
    if not all(A.read(m) for m in a.memo):
        sys.exit("メモのファイルがない")
    memo = A.SEP.join(f"# メモ（{m}）\n\n{A.read(m)}" for m in a.memo)
    ctx = A.SEP.join([A.canon_context(), A.section("これまでのあらすじ", A.doc("synopsis")),
                      A.section("オーナーの目", A.doc("owner_eye")), A.section("オーナーが直した例", A.doc("bad_examples"))])
    if a.after:
        ep = a.after
        body = A.read(f"episodes/current/{ep}.md")
        if not body:
            sys.exit(f"episodes/current/{ep}.md がない")
        prompt = (f"{PROMPT_AFTER}\n採用した話：{ep}（メモの中の {ep} の項が計画）{A.SEP}{ctx}{A.SEP}{memo}{A.SEP}"
                  f"# 採用版のまとめ（{ep}）\n\n{A.read(f'episodes/{ep}/notes/summary.md')}{A.SEP}# 採用版の本文（{ep}）\n\n{body}\n")
        stem = f"after-{ep}"
    else:
        scope = f"対象の話：{'、'.join(a.episodes)}（ほかの話は受け渡しの確認にだけ使う）" if a.episodes else "対象の話：メモの全話"
        cfg = A.config()
        market = A.SEP.join(f"# 市場の調べ（{m}）\n\n{A.read(m)}" for m in cfg.get("market", []) if A.read(m))
        story = any(Path(m).parts[0] == "chapters" for m in a.memo)  # 章のあらすじのときだけ（各話のメモには付けない）
        extra = (PROMPT_MARKET + A.SEP + market) if (market and story) else ""
        prompt = f"{PROMPT}{extra}\n{scope}{A.SEP}{ctx}{A.SEP}{memo}\n"
        stem = Path(a.memo[0]).stem
    out_dir = A.WORK / "blocks" / "notes"
    out_dir.mkdir(parents=True, exist_ok=True)
    jobs = [(n, prompt, (n, k)) for n in A.agents(a.agent) for k in range(1, a.runs + 1)]
    for (name, k), text, err in A.run_many(jobs, a.model, a.effort):
        if err:
            print(f"{name}: {err}")
            continue
        out = out_dir / f"memo-{stem}-{name}-{k}.md"
        print(A.write(out, f"# メモの監査 {' '.join(a.memo)}（{name} {k}回目）\n\n{text}"))


if __name__ == "__main__":
    main()
